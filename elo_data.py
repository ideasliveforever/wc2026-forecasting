def elo_win_prob(team_a, team_b):
    """P(team_a wins) from ELO. Returns None if teams not found."""
    elo_a = ELO_RATINGS.get(team_a.lower())
    elo_b = ELO_RATINGS.get(team_b.lower())
    if elo_a is None or elo_b is None:
        return None
    return 1.0 / (1.0 + 10 ** ((elo_b - elo_a) / 400))